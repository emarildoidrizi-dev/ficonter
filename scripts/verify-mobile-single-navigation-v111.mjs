import fs from 'node:fs';
const read = p => fs.readFileSync(p,'utf8');
const expect = (c,m) => { if(!c) throw new Error(m); };
const settings = read('components/SettingsWorkspace.tsx');
const sidebar = read('components/Sidebar.tsx');
const business = read('components/BusinessSidebar.tsx');
const boost = read('components/NavigationSpeedBoost.tsx');
const layout = read('app/layout.tsx');
let n=0; const ok=(c,m)=>{expect(c,m);n++};
ok(settings.includes('if (current === target && active === id && mobileDetailOpen) return;'), 'Settings must ignore the already-open child screen.');
ok(settings.includes('window.history.pushState(null, "", target);'), 'Phone Settings must perform one local history update.');
ok(settings.includes('setActive(id);') && settings.includes('setMobileDetailOpen(true);'), 'Phone Settings must switch visible content immediately.');
ok(!/function openSettingsSection[\s\S]{0,900}router\.push\(target/.test(settings), 'Settings must not add a second router navigation on mobile.');
ok(sidebar.includes('if (currentRoute === href) return;'), 'Profile/header routes must ignore same route.');
ok(sidebar.includes('resolvedTarget && resolvedTarget !== currentRoute'), 'Personal Back must guard same target.');
ok(business.includes('resolvedTarget && resolvedTarget !== currentRoute'), 'Business Back must guard same target.');
ok(boost.includes('lastAnimatedRouteKey.current !== routeKey'), 'Transition must not replay for same route key.');
ok(boost.includes('lastAnimatedRouteKey.current = routeKey;'), 'Animated route key must be recorded.');
ok(layout.includes('import "./mobile-page-stack.css";'), 'Single page-stack stylesheet must be loaded.');
ok(!layout.includes('import "./mobile-screen-stack.css";'), 'Legacy second page transition stylesheet must stay unloaded.');
console.log(`Mobile single-navigation V1.11 verification passed (${n}/${n}).`);
