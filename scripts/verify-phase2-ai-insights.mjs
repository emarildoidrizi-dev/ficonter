import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const failures = [];
let passed = 0;

function read(relative) {
  const file = path.join(root, relative);
  if (!fs.existsSync(file)) {
    failures.push(`Missing ${relative}`);
    return "";
  }
  return fs.readFileSync(file, "utf8");
}

function check(name, condition) {
  if (condition) passed += 1;
  else failures.push(name);
}

const required = [
  "app/dashboard/insights/page.tsx",
  "app/api/wealth/ai-insights/route.ts",
  "components/AiInsights.tsx",
  "components/AiInsights.module.css",
  "lib/wealth/aiInsights.ts",
  "supabase/phase2_ai_insights.sql",
];

for (const file of required) {
  check(`Required file exists: ${file}`, fs.existsSync(path.join(root, file)));
}

const route = read("app/api/wealth/ai-insights/route.ts");
const engine = read("lib/wealth/aiInsights.ts");
const component = read("components/AiInsights.tsx");
const sql = read("supabase/phase2_ai_insights.sql");
const sidebar = read("components/Sidebar.tsx");
const page = read("app/dashboard/insights/page.tsx");
const pkg = JSON.parse(read("package.json") || "{}");

check("Smart route requires same-origin requests", route.includes("isSameOriginRequest"));
check("Smart route authenticates the user", route.includes("supabase.auth.getUser"));
check("Smart route has no OpenAI network request", !route.includes("api.openai.com") && !route.includes("OPENAI_API_KEY"));
check("Smart report is generated by the shared engine", route.includes("generateSmartInsightReport"));
check("Smart route caches reports by fingerprint", route.includes("data_fingerprint") && route.includes("AI_INSIGHTS_CACHE_HOURS"));
check("Smart route prevents rapid duplicate generation", route.includes("GENERATION_COOLDOWN_MS") && route.includes(", 429"));
check("Smart route supports private history deletion", route.includes("export async function DELETE"));
check("No raw transaction query in Smart route", !route.includes('.from("transactions")'));
check("Smart engine composes existing Cash Flow source", engine.includes("calculateCashFlowIntelligence"));
check("Smart engine composes existing Financial Independence source", engine.includes("calculateFinancialIndependence"));
check("Smart engine reuses existing Wealth Score", engine.includes("calculateWealthScore"));
check("Smart engine exports deterministic report generator", engine.includes("export function generateSmartInsightReport"));
check("Smart engine fingerprints reports independently", engine.includes("smart-v2-"));
check("Smart engine identifies itself", engine.includes("FICONTER Smart Engine v2"));
check("Smart engine creates verified evidence keys", engine.includes("AiEvidenceKey") && engine.includes("evidenceKeysOnly"));
check("Empty accounts remain unassessed", component.includes("Smart insights are not assessed yet") && engine.includes("const assessed"));
check("Generation is explicitly on demand", component.includes("Generate smart report") && component.includes("No external AI request"));
check("UI explains cost-free private analysis", component.includes("Cost-free private analysis") && component.includes("financial information is sent to OpenAI"));
check("Old AI consent requirement is removed", !component.includes("Enable AI insights") && !route.includes("consent_required"));
check("Old API configuration error is removed", !component.includes("AI service configuration is required"));
check("Snapshots remain protected by RLS", sql.includes("alter table public.ai_insight_snapshots enable row level security"));
check("Aggregate function reuses existing Phase 2 RPCs", sql.includes("get_cash_flow_intelligence_inputs_v2") && sql.includes("get_financial_independence_inputs"));
check("Aggregate function is authenticated only", sql.includes("grant execute on function public.get_ai_insights_inputs() to authenticated"));
check("Smart page is authenticated", page.includes('redirect("/login")'));
check("Smart page only loads Smart Engine snapshots", page.includes("SMART_INSIGHTS_ENGINE_VERSION") && page.includes('.eq("model", SMART_INSIGHTS_ENGINE_VERSION)'));
check("Sidebar exposes Smart insights", sidebar.includes('"/dashboard/insights"') && sidebar.includes('"Smart Insights"'));
check("Component refreshes on financial realtime changes", component.includes("postgres_changes") && component.includes("ficonter:data-changed"));
check("Report displays deterministic evidence values", component.includes("evidenceValue") && component.includes("EvidenceChips"));
check("Report includes a 90-day action plan", component.includes("90-DAY ACTION PLAN"));
check("Private report history can be cleared", component.includes("Clear report history") && component.includes("Clear Smart Insight history"));
check("Existing verification command remains registered", pkg.scripts?.["verify:phase2-ai"] === "node scripts/verify-phase2-ai-insights.mjs");

if (failures.length) {
  console.error(`Phase 2 Smart Insights verification failed (${failures.length} issues):`);
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}

console.log(`Phase 2 Smart Insights verification passed (${passed} checks).`);
